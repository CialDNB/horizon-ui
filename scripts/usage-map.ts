interface MapRow extends ReportRow {
    batch: Batch;
    h: string;
    mapStatus: Status;
    note: string;
    family: string;
}

function toMapRows(report: Report): MapRow[] {
    return report.components.map((r) => {
        const cur = curation[r.name] ?? curation[parseVersion(r.name).base];
        if (!cur) throw new Error(`No curation entry for ${r.name}`);
        const drawer = r.name === 'Drawer' || /^DrawerV\d+$/.test(r.name);
        const h = drawer ? (r.horizon ?? cur.horizon) : cur.horizon;
        let mapStatus: Status = r.status ?? 'todo';
        if (mapStatus === 'todo' && cur.status) mapStatus = cur.status;
        const unused = r.count + r.typeCount === 0;
        let note = cur.note;
        if (mapStatus === 'superseded') {
            note = unused
                ? 'Lower version of the family; not ported (unused-in-customer360).'
                : `Lower version of the family; not ported. Migrate call sites to \`${h}\`.`;
            if (cur.supersededNote) note += ` ${cur.supersededNote}`;
        } else if (mapStatus === 'skip' && unused) {
            const rest = note
                .replace(
                    /^(Skip|Docs-only; skip|App-specific; skip)(\s+unless requested)?[;.,]?\s*/,
                    ''
                )
                .trim();
            note = `unused-in-customer360. ${
                rest ? rest.charAt(0).toUpperCase() + rest.slice(1) + ' ' : ''
            }Recommend skip porting unless requested.`.replace(/\.\s*\./g, '.');
        } else if (unused && mapStatus === 'todo') {
            note = `unused-in-customer360 (direct imports); ${note}`;
        }
        return {
            ...r,
            batch: cur.batch,
            h,
            mapStatus,
            note,
            family: familyOf(r.name),
        };
    });
}

const version = (n: string) => {
    const m = /[Vv](\d+)$/.exec(n);
    return m?.[1] ? Number(m[1]) : 1;
};

function tableRow(r: MapRow): string {
    const target =
        r.mapStatus === 'no-equivalent'
            ? '(none)'
            : r.mapStatus === 'skip'
              ? `\`${r.h}\` (not ported)`
              : `\`${r.h}\``;
    return `| \`${r.name}\` | ${target} | ${r.mapStatus} | ${r.note} | ${r.count} | ${r.files} | ${r.typeCount} |`;
}

const TABLE_HEAD =
    '| x-core component | horizon-ui component | status | API differences | customer360 runtime imports | runtime files | type-only imports |\n|---|---|---|---|---|---|---|';

export function renderRegion(report: Report): string {
    const rows = toMapRows(report);
    const sorted = [...rows].sort(
        (a, b) =>
            (b.familyFiles ?? 0) - (a.familyFiles ?? 0) ||
            (b.familyCount ?? 0) - (a.familyCount ?? 0) ||
            a.family.localeCompare(b.family) ||
            version(a.name) - version(b.name)
    );
    const families = new Map<string, MapRow[]>();
    for (const r of sorted) {
        families.set(r.family, [...(families.get(r.family) ?? []), r]);
    }
    const used = [...families.values()].filter(
        (m) =>
            (m[0]?.familyCount ?? 0) + m.reduce((n, r) => n + r.typeCount, 0) >
            0
    );
    const countStatus = (s: Status) =>
        rows.filter((r) => r.mapStatus === s).length;
    const direct = rows.filter((r) => r.count + r.typeCount > 0).length;

    const supersededUse = [...families.values()]
        .map((m) => ({
            old: m.find((r) => r.mapStatus === 'superseded' && r.files > 0),
            latest: m.find((r) => r.mapStatus !== 'superseded'),
        }))
        .filter(
            (x): x is { old: MapRow; latest: MapRow } =>
                x.old !== undefined &&
                x.latest !== undefined &&
                x.latest.name !== x.old.name
        )
        .sort((a, b) => b.old.files - a.old.files)
        .slice(0, 6)
        .map(
            (x) =>
                `\`${x.old.name}\` ${x.old.files} files vs \`${x.latest.name}\` ${x.latest.files}`
        );

    const familyFiles = (name: string) =>
        rows.find((r) => r.name === name)?.familyFiles ?? 0;
    const notInPlan = NOT_IN_PLAN.map(
        (n) => `\`${n}\` (${familyFiles(n)} files)`
    ).join(', ');

    const top = [...families.values()]
        .filter((m) => (m[0]?.familyFiles ?? 0) > 0)
        .slice(0, 25);
    const topTable = top.map((m, i) => {
        const first = m[0];
        const latest = m.find((r) => r.mapStatus !== 'superseded') ?? first;
        if (!first || !latest) return '';
        const imports = m.reduce((n, r) => n + r.count, 0);
        return `| ${i + 1} | ${[...m]
            .sort((a, b) => version(a.name) - version(b.name))
            .map((r) => `\`${r.name}\``)
            .join(
                ' + '
            )} | \`${latest.h}\` | ${latest.batch} | ${first.familyFiles} | ${imports} |`;
    });

    const n = (name: string) => {
        const r = rows.find((x) => x.name === name);
        return r ? `${r.files} files` : '0 files';
    };

    const other = report.other;
    const iconRow = other.find((o) => o.name === '@cialdnb/x-core/icons');
    const unsuffixed = iconRow
        ? Object.entries(iconRow.imports)
              .filter(([name]) => !name.endsWith('Icon'))
              .reduce((sum, [, c]) => sum + c, 0)
        : 0;
    const imp = (comp: string, name: string) =>
        rows.find((r) => r.name === comp)?.imports[name] ?? 0;

    const lines: string[] = [];
    lines.push(`## Summary

Counts are **runtime** imports and distinct files; type-only imports (\`import type\`, \`import { type X }\`, and names x-core exports only as types such as \`ChipProps\`) are shown separately and excluded from ranking, because they vanish at build time. Everything is ranked by runtime files.

- ${rows.length} x-core components (${used.length} version families imported directly by customer360; ${rows.length - direct} components have no direct import).
- Status: ${countStatus('todo')} todo, ${countStatus('done')} done, ${countStatus('superseded')} superseded, ${countStatus('no-equivalent')} no-equivalent, ${countStatus('skip')} skip.
- **Superseded versions are still heavily used by customer360**: ${supersededUse.join('; ')}. Migrating those call sites targets the single horizon-ui name.
- Used by customer360 but missing from the plan's batch lists: ${notInPlan}. See the "Usage-ordered batch lists" subsections under Tasks 10-13 in the plan.

### Top 25 by family runtime files (all versions of a family combined)

| # | family | horizon-ui | batch | runtime files (family) | runtime imports (family) |
|---|---|---|---|---|---|
${topTable.join('\n')}

### Porting order recommendation

1. Finish Batch 1 around real usage: Typography (${n('Typography')}), Chip (${n('Chip')}), Spinner from CircularProgress (${n('CircularProgress')}), Alert, Badge, Avatar, Separator, IconButton, Progress. Button is done.
2. Batch 2 inputs next because every form screen needs them together: Input (TextField ${n('TextField')}, TextInput ${n('TextInput')}) with FormField, Select, Checkbox, RadioGroup, Switch, Autocomplete (Combobox), then overlays Dialog, Tooltip, Popover, Drawer, Toast, then SplitButton and Filter (need DropdownMenu/Popover).
3. Batch 3 starts with Table (${n('Table')}, the most-used composite) and Card (+ InsightsCard, LevelCard), then Tabs, Accordion, Timeline, Pagination, then NavigationDrawer + AppBar + Layout as one unit (customer360 consumes it through \`LayoutV2\`).
4. Batch 4 only on request: the live items are the charts (AreaChart, StackedBarChart, VerticalBarChart) and the pickers (DatePicker, DateRangePicker); most chart, legend and map variants have no imports.
5. Skip everything marked \`skip\` and \`unused-in-customer360\` unless a consumer asks (il-acl-client uses Breadcrumbs, PasswordField, InputCompany, FilterInput, DualDataCard, SearchBar and Timeline, which customer360 does not).
`);
    for (const b of [1, 2, 3, 4] as const) {
        lines.push(
            `## ${BATCH_TITLES[b]}\n\nOrdered by family runtime files (descending); versions of one family are adjacent.\n\n${TABLE_HEAD}\n${sorted
                .filter((r) => r.batch === b)
                .map(tableRow)
                .join('\n')}\n`
        );
    }
    lines.push(`## Imports that are not components

These need migration answers in Task 20 (consumer integration pilot) even though they are not in the component list.

| import path | runtime imports | runtime files | type-only imports | what is imported | horizon-ui answer |
|---|---|---|---|---|---|
${other
    .map((o) => {
        const names = Object.entries(o.imports)
            .sort((a, b) => b[1] - a[1])
            .slice(0, 6)
            .map(([k, c]) => `\`${k}\` ${c}`)
            .join(', ');
        let ans = OTHER_ANSWERS[o.name] ?? 'Unclassified.';
        if (o.name === '@cialdnb/x-core/icons')
            ans = `${unsuffixed} of ${o.count} imports use Phosphor names without the \`Icon\` suffix (for example \`Info\`, \`CaretLeft\`). ${ans}`;
        return `| \`${o.name}\` | ${o.count} | ${o.files} | ${o.typeCount} | ${names} | ${ans} |`;
    })
    .join('\n')}

Hooks and types that live under component folders (for example \`useDialog\`, \`TableColumnSettings\`, \`SelectOption\`, \`ChipColor\`) are attributed to their owning component above. Hooks are not exported by horizon-ui yet: \`useDialog\` (il-acl-client, 12 imports) has no equivalent and must be designed with Dialog.

### Follow-ups: shared enums and constants imported from superseded components

These runtime imports are attributed to a superseded component, so porting only the latest version would silently drop them. The successor must export them (or the call sites must change).

| import | from | runtime imports | successor must provide |
|---|---|---|---|
| \`LayoutEnum\` | \`Layout/Layout.types\` (superseded \`Layout\`) | ${imp('Layout', 'LayoutEnum')} | \`Layout\` (port of \`LayoutV2\`) |
| \`drawerWidth\` | \`Drawer\` (superseded plain Drawer) | ${imp('Drawer', 'drawerWidth')} | \`NavigationDrawer\` |
| \`drawerCollapsedWidth\` | \`Drawer\` (superseded plain Drawer) | ${imp('Drawer', 'drawerCollapsedWidth')} | \`NavigationDrawer\` |

### Other consumers of x-core (informational)

\`package.json\` files under \`/Users/simonmor/dnb\` that depend on \`@cialdnb/x-core\`: \`customer360/client\` (2.2.30) and \`il-acl-client\` (^2.2.22). No dependency in il-acl, mycial-backend, autobahn, workflow-engine, c360-api, projectx-backend or the deployment repos. il-acl-client also imports Breadcrumbs, PasswordField, InputCompany, SearchBar, FilterInput, Timeline, DualDataCard and the \`Dialog/useDialog\` hook (12 imports), which customer360 does not. Run \`scripts/usage-report.ts\` on it for current numbers.
`);
    return lines.join('\n');
}

export function replaceRegion(doc: string, region: string): string {
    const a = doc.indexOf(START);
    const b = doc.indexOf(END);
    if (a < 0 || b < a) throw new Error('usage markers not found');
    return `${doc.slice(0, a + START.length)}\n\n${region.trim()}\n\n${doc.slice(b)}`;
}

async function main(argv: string[]): Promise<void> {
    const flag = (name: string) => {
        const i = argv.indexOf(name);
        return i >= 0 ? argv[i + 1] : undefined;
    };
    const dir = argv.find(
        (a, i) => !a.startsWith('--') && !argv[i - 1]?.startsWith('--')
    );
    if (!dir) {
        console.error(
            'usage: tsx scripts/usage-map.ts <client-dir> [--x-core <dir>] [--map <file>]'
        );
        process.exit(1);
    }
    const xCore = flag('--x-core') ?? resolve(dir, '../../x-core');
    if (!existsSync(join(xCore, 'src/components')))
        throw new Error(`x-core not found at ${xCore}; pass --x-core`);
    const file = flag('--map') ?? resolve('docs/migration/component-map.md');
    const report = analyze(dir, xCore);
    const text = replaceRegion(
        readFileSync(file, 'utf8'),
        renderRegion(report)
    );
    const config = (await resolveConfig(file)) ?? {};
    writeFileSync(file, await format(text, { ...config, filepath: file }));
    console.log(`updated ${file}`);
}

