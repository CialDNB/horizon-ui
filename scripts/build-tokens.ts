import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { borderColor, borderWidth } from '../src/tokens/borders';
import { borderRadius } from '../src/tokens/borderRadius';
import { brands, brandTypography, semanticKeys } from '../src/tokens/brands';
import type { Brand, BrandTypography } from '../src/tokens/brands';
import * as colors from '../src/tokens/colors';
import { iconSize } from '../src/tokens/iconography';
import { duration, easing } from '../src/tokens/motion';
import { elevation } from '../src/tokens/shadows';
import { dialogWidth, spacingBase } from '../src/tokens/spacing';
import { fontSize, lineHeight } from '../src/tokens/typography';

type Decl = readonly [name: string, value: string | number];

const INDENT = '    ';
const kebab = (s: string) => s.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);
const slug = (role: string) => role.replace('/', '-');

const block = (selector: string, decls: readonly Decl[]): string =>
    `${selector} {\n${decls
        .map(([name, value]) => `${INDENT}--${name}: ${value};`)
        .join('\n')}\n}\n`;

const scale = (
    prefix: string,
    tokens: Readonly<Record<string, string | number>>,
    unit = ''
): Decl[] =>
    Object.entries(tokens).map(([k, v]) => [`${prefix}-${k}`, `${v}${unit}`]);

const colorScales = [
    'grey',
    'blue',
    'indigo',
    'cyan',
    'lightBlue',
    'red',
    'amber',
    'teal',
    'green',
    'orange',
    'pink',
    'purple',
    'blueGrey',
] as const;

const primitiveColors = (): Decl[] => [
    ...colorScales.flatMap((name) => scale(`hz-${kebab(name)}`, colors[name])),
    ['hz-white', colors.common.white],
    ['hz-black', colors.common.black],
    ...scale('hz-gradient', colors.gradients),
];

const semantic = (brand: Brand): Decl[] =>
    semanticKeys.map((key) => [key, brands[brand][key]]);

const typography = (t: BrandTypography): Decl[] => [
    ['font-family', t.fontFamily],
    ...scale('font-weight', t.fontWeight),
    ...Object.entries(t.typeScale).flatMap(([role, s]): Decl[] => [
        [`text-${slug(role)}-size`, s.fontSize],
        [`text-${slug(role)}-line-height`, s.lineHeight],
        [`text-${slug(role)}-weight`, s.fontWeight],
    ]),
];

const sameTypography = (brand: Brand): boolean =>
    JSON.stringify(brandTypography[brand]) ===
    JSON.stringify(brandTypography.cial);

const nonColor = (): Decl[] => [
    ['spacing', `${spacingBase}px`],
    ...scale('dialog-width', dialogWidth, 'px'),
    ...scale('radius', borderRadius, 'px'),
    ['radius', `${borderRadius.lg}px`],
    ...scale('shadow', elevation),
    ...scale('border-width', borderWidth),
    ...scale('border-color', borderColor),
    ...scale('duration', duration, 'ms'),
    ...scale('ease', easing),
    ...scale('icon-size', iconSize, 'px'),
    ...scale('font-size', fontSize),
    ...scale('line-height', lineHeight),
];

/**
 * Generates the token stylesheet. Every variable is scoped to `.hz-root`
 * (never `:root`) so it cannot collide with consumer CSS. The cial brand is the
 * default on `.hz-root`; dnb and il override via `data-brand`.
 */
export function buildTokensCss(): string {
    const parts = [
        '/* Generated by scripts/build-tokens.ts. Do not edit. */\n',
        block('.hz-root', [
            ...primitiveColors(),
            ...semantic('cial'),
            ...nonColor(),
            ...typography(brandTypography.cial),
        ]),
        ...(['dnb', 'il'] as const).map((brand) =>
            block(`.hz-root[data-brand='${brand}']`, [
                ...semantic(brand),
                ...(sameTypography(brand)
                    ? []
                    : typography(brandTypography[brand])),
            ])
        ),
    ];
    return parts.join('\n');
}

const isMain =
    process.argv[1] !== undefined &&
    import.meta.url === pathToFileURL(process.argv[1]).href;

if (isMain) {
    const out = join(
        dirname(fileURLToPath(import.meta.url)),
        '..',
        'src',
        'styles',
        'tokens.css'
    );
    mkdirSync(dirname(out), { recursive: true });
    writeFileSync(out, buildTokensCss());
    console.warn(`wrote ${out}`);
}
