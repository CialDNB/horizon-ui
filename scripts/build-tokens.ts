import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { borderColor, borderWidth } from '../src/tokens/borders';
import { borderRadius } from '../src/tokens/borderRadius';
import { breakpoints } from '../src/tokens/breakpoints';
import { brands, brandTypography, semanticKeys } from '../src/tokens/brands';
import type { Brand, BrandTypography } from '../src/tokens/brands';
import * as colors from '../src/tokens/colors';
import { iconSize } from '../src/tokens/iconography';
import { duration, easing } from '../src/tokens/motion';
import { elevation } from '../src/tokens/shadows';
import { dialogWidth, spacingBase } from '../src/tokens/spacing';
import { fontSize, lineHeight, typeScale } from '../src/tokens/typography';

type Decl = readonly [name: string, value: string | number];

const INDENT = '    ';
const GENERATED = '/* Generated by scripts/build-tokens.ts. Do not edit. */\n';
const kebab = (s: string) => s.replace(/[A-Z]/g, (c) => `-${c.toLowerCase()}`);
const slug = (role: string) => role.replace('/', '-');

/**
 * Converts a rem token (authored against a 16px root) to px. Emitted type sizes
 * are px because consumers on x-core Legacy set `html { font-size: 14px }`,
 * which would otherwise shrink every rem value by 12.5% (ADR 0001).
 */
const px = (rem: string): string => {
    if (!/^\d*\.?\d+rem$/.test(rem)) throw new Error(`not a rem value: ${rem}`);
    return `${parseFloat(rem) * 16}px`;
};

const pxScale = (tokens: Readonly<Record<string, string>>) =>
    Object.fromEntries(Object.entries(tokens).map(([k, v]) => [k, px(v)]));

const block = (selector: string, decls: readonly Decl[]): string =>
    `${selector} {\n${decls
        .map(([name, value]) => `${INDENT}--${name}: ${value};`)
        .join('\n')}\n}\n`;

const scale = (
    prefix: string,
    tokens: Readonly<Record<string, string | number>>,
    unit = ''
): Decl[] =>
    Object.entries(tokens).map(([k, v]) => [
        `${prefix}-${kebab(k)}`,
        `${v}${unit}`,
    ]);

const colorScales = [
    'grey',
    'blue',
    'indigo',
    'cyan',
    'lightBlue',
    'red',
    'amber',
    'teal',
    'green',
    'orange',
    'pink',
    'purple',
    'blueGrey',
] as const;

const primitiveColors = (): Decl[] => [
    ...colorScales.flatMap((name) => scale(`hz-${kebab(name)}`, colors[name])),
    ['hz-white', colors.common.white],
    ['hz-black', colors.common.black],
    ...scale('hz-gradient', colors.gradients),
];

const semantic = (brand: Brand): Decl[] =>
    semanticKeys.map((key) => [key, brands[brand][key]]);

const typography = (t: BrandTypography): Decl[] => [
    ['font-family', t.fontFamily],
    ...scale('font-weight', t.fontWeight),
    ...Object.entries(t.typeScale).flatMap(([role, s]): Decl[] => [
        [`text-${slug(role)}-size`, px(s.fontSize)],
        [`text-${slug(role)}-line-height`, px(s.lineHeight)],
        [`text-${slug(role)}-weight`, s.fontWeight],
    ]),
];

const sameTypography = (brand: Brand): boolean =>
    JSON.stringify(brandTypography[brand]) ===
    JSON.stringify(brandTypography.cial);

const nonColor = (): Decl[] => [
    ['spacing', `${spacingBase}px`],
    ...scale('dialog-width', dialogWidth, 'px'),
    ...scale('radius', borderRadius, 'px'),
    // shadcn --radius is the interactive-element radius: lg (20px) per spec
    ['radius', `${borderRadius.lg}px`],
    ...scale('shadow', elevation),
    ...scale('border-width', borderWidth),
    ...scale('border-color', borderColor),
    ...scale('duration', duration, 'ms'),
    ...scale('ease', easing),
    ...scale('icon-size', iconSize, 'px'),
    ...scale('font-size', pxScale(fontSize)),
    ...scale('line-height', pxScale(lineHeight)),
];

/**
 * Generates the token stylesheet. Every variable is scoped to `.hz-root`
 * (never `:root`) so it cannot collide with consumer CSS. The cial brand is the
 * default on `.hz-root`; dnb and il override via `data-brand`.
 */
export function buildTokensCss(): string {
    const parts = [
        GENERATED,
        block('.hz-root', [
            ...primitiveColors(),
            ...semantic('cial'),
            ...nonColor(),
            ...typography(brandTypography.cial),
        ]),
        ...(['dnb', 'il'] as const).map((brand) =>
            block(`.hz-root[data-brand='${brand}']`, [
                ...semantic(brand),
                ...(sameTypography(brand)
                    ? []
                    : typography(brandTypography[brand])),
            ])
        ),
    ];
    return parts.join('\n');
}

/**
 * Generates the Tailwind `@theme` mapping. `inline` makes utilities reference
 * values directly (`bg-primary` -> `var(--primary)`), so Tailwind emits no theme
 * variables on `:root`; colours resolve against the `.hz-root` scoped vars, so
 * `data-brand` subtrees switch brand. Default namespaces we own are reset so
 * only Horizon tokens exist (no `sm/md/lg/xl`, no primitive palette).
 */
export function buildThemeCss(): string {
    const decls: Decl[] = [
        ['breakpoint-*', 'initial'],
        ...Object.entries(breakpoints)
            .filter(([, v]) => v > 0)
            .map(([k, v]): Decl => [`breakpoint-${k}`, `${v}px`]),
        ['color-*', 'initial'],
        ...semanticKeys.map((key): Decl => [`color-${key}`, `var(--${key})`]),
        ['spacing', `${spacingBase}px`],
        ['radius-*', 'initial'],
        ...scale('radius', borderRadius, 'px'),
        ['shadow-*', 'initial'],
        ...scale('shadow', elevation),
        ['ease-*', 'initial'],
        ...scale('ease', easing),
        ['default-transition-duration', `${duration.normal}ms`],
        ['default-transition-timing-function', easing.standard],
        ['font-*', 'initial'],
        ['font-sans', 'var(--font-family)'],
        ['font-weight-*', 'initial'],
        ...scale('font-weight', brandTypography.cial.fontWeight),
        // Type comes only from the type-scale utilities in typography.css.
        ['text-*', 'initial'],
    ];
    return GENERATED + '\n' + block('@theme inline', decls);
}

/**
 * Generates one `@utility` per type-scale role. Values come from the `.hz-root`
 * variables so a brand with its own typography overrides them. Every role is
 * safelisted at every breakpoint so it ships in the precompiled stylesheet.
 */
export function buildTypographyCss(): string {
    const names = Object.keys(typeScale).map(slug);
    const variants = Object.entries(breakpoints)
        .filter(([, v]) => v > 0)
        .map(([k]) => `${k}:`);
    const utilities = names.map(
        (name) =>
            `@utility text-${name} {\n` +
            `${INDENT}font-family: var(--font-family);\n` +
            `${INDENT}font-size: var(--text-${name}-size);\n` +
            `${INDENT}line-height: var(--text-${name}-line-height);\n` +
            `${INDENT}font-weight: var(--text-${name}-weight);\n}\n`
    );
    const safelist = `@source inline('hz:{,${variants.join(',')}}text-{${names.join(',')}}');\n`;
    return [GENERATED, safelist, ...utilities].join('\n');
}

const isMain =
    process.argv[1] !== undefined &&
    import.meta.url === pathToFileURL(process.argv[1]).href;

if (isMain) {
    const dir = join(
        dirname(fileURLToPath(import.meta.url)),
        '..',
        'src',
        'styles'
    );
    mkdirSync(dir, { recursive: true });
    const outputs = {
        'tokens.css': buildTokensCss(),
        'theme.css': buildThemeCss(),
        'typography.css': buildTypographyCss(),
    };
    for (const [file, content] of Object.entries(outputs)) {
        writeFileSync(join(dir, file), content);
        console.warn(`wrote ${join(dir, file)}`);
    }
}
